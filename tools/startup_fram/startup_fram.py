#!/usr/bin/env python3
"""Host generator and inspector for the 48-byte Startup FRAM image (``SSP1``).

The tool is deliberately offline: it reads and writes local files only. It never
opens a probe, serial port or USB device, so it cannot arm, provision or reset a
spacecraft by itself.

    python3 tools/startup_fram/startup_fram.py generate \
        --boot-count 0 --adcs-sensors Sun0,Mag1 --binary /tmp/startup.bin \
        --header /tmp/startup_image.h

    python3 tools/startup_fram/startup_fram.py inspect /tmp/startup.bin

Exit status is 0 on success, 1 when the arguments or the image violate the
contract, and 2 for command-line usage errors.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import startup_image  # noqa: E402  (import after sys.path setup for `python3 <path>` runs)


def _parse_int(text: str) -> int:
    try:
        return int(text, 0)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f"{text!r} is not an integer (decimal or 0x-prefixed hex)"
        ) from None


def _header_text(image: bytes, symbol: str) -> str:
    decoded = startup_image.validate_image(image)
    guard = f"{symbol}_H"
    lines = [
        "/* Generated by tools/startup_fram/startup_fram.py - do not edit.",
        f" * Startup FRAM image, format SSP1, {startup_image.IMAGE_SIZE} bytes,",
        f" * covering byte addresses 0..{startup_image.LAST_IMAGE_ADDR}:",
        f" *   [{startup_image.BOOT_COUNTER_ADDR}..{startup_image.ADCS_MASK_ADDR + 3}]"
        " boot counter, 4 bytes LE",
        f" *   [{startup_image.ADCS_MASK_ADDR}..{startup_image.SLOT_A_ADDR - 1}]"
        " ADCS mask, 4 bytes LE",
        f" *   [{startup_image.SLOT_A_ADDR}..{startup_image.SLOT_A_ADDR + startup_image.SLOT_SIZE - 1}]"
        " startup slot A, 20 bytes",
        f" *   [{startup_image.SLOT_B_ADDR}..{startup_image.SLOT_B_ADDR + startup_image.SLOT_SIZE - 1}]"
        " startup slot B, 20 bytes",
        " */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define {symbol}_SIZE {startup_image.IMAGE_SIZE}u",
        f"#define {symbol}_BOOT_COUNT 0x{decoded.boot_count:08X}u",
        f"#define {symbol}_ADCS_MASK 0x{decoded.adcs_mask:08X}u",
        f"#define {symbol}_ARMED {1 if decoded.armed else 0}u",
        "",
        f"static const uint8_t {symbol}[{symbol}_SIZE] = {{",
    ]
    for offset in range(0, len(image), 8):
        chunk = ", ".join(f"0x{byte:02X}" for byte in image[offset:offset + 8])
        lines.append(f"    {chunk},")
    lines += ["};", "", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def _write_exclusive(path: pathlib.Path, data: bytes, overwrite: bool) -> None:
    mode = "wb" if overwrite else "xb"
    try:
        with open(path, mode) as handle:
            handle.write(data)
    except FileExistsError:
        raise startup_image.StartupImageError(
            f"{path} already exists; refusing to overwrite without --overwrite"
        ) from None


def _slot_payloads(decoded: "startup_image.DecodedImage") -> list[dict[str, object]]:
    slots: list[dict[str, object]] = []
    for index, raw in enumerate(decoded.raw_slots):
        entry: dict[str, object] = {
            "addr": startup_image.SLOT_ADDRS[index],
            "valid": not decoded.slot_errors[index],
            "problems": decoded.slot_errors[index],
        }
        if not decoded.slot_errors[index]:
            slot = startup_image.StartupSlot.decode(raw)
            entry.update(
                {
                    "sequence": slot.sequence,
                    "state": int(slot.state),
                    "state_name": startup_image.state_name(int(slot.state)),
                    "attempts_used": slot.attempts_used,
                    "remaining_ms": slot.remaining_ms,
                    "armed": slot.armed,
                }
            )
        slots.append(entry)
    return slots


def _describe(image: bytes) -> tuple[list[str], startup_image.DecodedImage]:
    decoded = startup_image.validate_image(image)
    lines = [
        f"format          {startup_image.TAG.decode()} (tag bytes 0..3 of each slot)",
        f"image length    {len(image)} bytes, addresses 0..{startup_image.LAST_IMAGE_ADDR}",
        f"boot counter    {decoded.boot_count} (uint32 LE @ {startup_image.BOOT_COUNTER_ADDR})",
        f"ADCS mask       0x{decoded.adcs_mask:08X} (uint32 LE @ {startup_image.ADCS_MASK_ADDR})",
        f"ADCS enabled    {', '.join(decoded.adcs_enabled) or '(none)'}",
        f"armed           {'YES - permits deployment' if decoded.armed else 'no'}",
    ]
    for index, raw in enumerate(decoded.raw_slots):
        base = startup_image.SLOT_ADDRS[index]
        errors = decoded.slot_errors[index]
        lines.append(
            f"slot {'AB'[index]}          bytes {base}..{base + startup_image.SLOT_SIZE - 1}"
        )
        if errors:
            lines.append(f"  INVALID       {'; '.join(errors)}")
            continue
        slot = startup_image.StartupSlot.decode(raw)
        lines += [
            f"  sequence      {slot.sequence}",
            f"  resume state  {int(slot.state)} ({startup_image.state_name(int(slot.state))})",
            f"  attempts used {slot.attempts_used}/{startup_image.ATTEMPT_LIMIT}",
            f"  remaining_ms  {slot.remaining_ms}",
            f"  flags         0x{slot.flags:02X}"
            f" (armed={'set' if slot.armed else 'clear'})",
            f"  commit marker 0x{raw[startup_image.MARKER_OFFSET]:02X} (valid)",
        ]
    if decoded.active_slot_index is not None:
        lines.append(
            f"active slot     {'AB'[decoded.active_slot_index]} (higher valid sequence wins)"
        )
    else:
        lines.append("active slot     none - the firmware would treat this device as an error")
    for problem in decoded.record_errors:
        lines.append(f"record problem  {problem}")
    lines.append(
        "loader verdict  "
        + ("comfortable: both slots valid" if decoded.valid else
           ("usable: one valid slot" if decoded.usable else "unusable"))
    )
    return lines, decoded


def cmd_generate(args: argparse.Namespace) -> int:
    if args.adcs_mask is None and args.adcs_sensors is None:
        raise startup_image.StartupImageError(
            "the ADCS mask must be selected explicitly: pass --adcs-mask or"
            " --adcs-sensors (no default is guessed)"
        )
    if args.adcs_mask is not None:
        mask = args.adcs_mask
    else:
        mask = startup_image.mask_from_names_text(args.adcs_sensors)
    if args.binary is None and args.header is None:
        raise startup_image.StartupImageError(
            "nothing to write: pass --binary and/or --header"
        )
    outputs = [path for path in (args.binary, args.header) if path is not None]
    if not args.overwrite:
        existing = [output for output in outputs if pathlib.Path(output).exists()]
        if existing:
            raise startup_image.StartupImageError(
                f"{', '.join(existing)} already exists; refusing to overwrite"
                " without --overwrite (no output was written)"
            )

    image = startup_image.fresh_image(args.boot_count, mask, armed=args.armed)
    decoded = startup_image.validate_image(image)
    if not decoded.valid:  # defensive: fresh_image cannot produce this
        raise startup_image.StartupImageError("; ".join(decoded.record_errors))
    if args.binary is not None:
        _write_exclusive(pathlib.Path(args.binary), image, args.overwrite)
    if args.header is not None:
        _write_exclusive(
            pathlib.Path(args.header),
            _header_text(image, args.header_symbol).encode("ascii"),
            args.overwrite,
        )

    print(f"wrote {startup_image.IMAGE_SIZE} bytes, schema {startup_image.TAG.decode()}"
          f"{' (binary: ' + args.binary + ')' if args.binary else ''}"
          f"{' (header: ' + args.header + ')' if args.header else ''}")
    for line in _describe(image)[0]:
        print(f"  {line}")
    print(f"  image hex     {image.hex()}")
    if decoded.armed:
        print("WARNING: this image is ARMED; the first boot may deploy the burn wire.")
    else:
        print("Unarmed image: the first boot stays inhibited and never deploys.")
    print("No device was contacted; write the image to hardware with the separate"
          " onboard provisioning build.")
    return 0


def cmd_inspect(args: argparse.Namespace) -> int:
    path = pathlib.Path(args.image)
    try:
        image = path.read_bytes()
    except OSError as exc:
        raise startup_image.StartupImageError(f"cannot read {path}: {exc}") from None
    try:
        lines, decoded = _describe(image)
        error: str | None = None
    except startup_image.StartupImageError as exc:
        lines, decoded, error = [f"INVALID: {exc}"], None, str(exc)

    if args.json:
        payload: dict[str, object] = {
            "path": str(path),
            "length": len(image),
            "hex": image.hex(),
            "valid": decoded is not None and decoded.valid,
            "usable": decoded is not None and decoded.usable,
            "error": error,
        }
        if decoded is not None:
            payload.update(
                {
                    "boot_count": decoded.boot_count,
                    "adcs_mask": f"0x{decoded.adcs_mask:08X}",
                    "adcs_enabled": decoded.adcs_enabled,
                    "armed": decoded.armed,
                    "active_slot": (
                        "AB"[decoded.active_slot_index]
                        if decoded.active_slot_index is not None
                        else None
                    ),
                    "record_errors": decoded.record_errors,
                    "slots": _slot_payloads(decoded),
                }
            )
        print(json.dumps(payload, indent=2, sort_keys=True))
    else:
        print(f"inspecting {path} ({len(image)} bytes)")
        for line in lines:
            print(f"  {line}")
        if decoded is not None and decoded.armed:
            print("WARNING: this image is ARMED; the next boot may deploy the burn wire.")
    return 0 if decoded is not None and decoded.valid else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="startup_fram.py",
        description=(
            "Generate or inspect the 48-byte Startup FRAM image (format SSP1)."
            " This tool never touches hardware."
        ),
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser(
        "generate",
        help="write a fresh INITIAL_CHECKS image as binary and/or C header",
        description=(
            "Write a fresh sequence-1 image: boot counter, ADCS mask and two"
            " identical INITIAL_CHECKS slots (attempts 0, remaining 1800000 ms)."
        ),
    )
    generate.add_argument(
        "--boot-count", type=_parse_int, required=True, metavar="N",
        help=f"boot counter to store, {startup_image.BOOT_COUNT_MAX} max"
             " (0xFFFFFFFF is a saturated counter and is rejected)",
    )
    group = generate.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--adcs-mask", type=_parse_int, metavar="MASK",
        help="ADCS enable mask, e.g. 0x00000000 or 0x1FFFFF; bits 21..31 reserved",
    )
    group.add_argument(
        "--adcs-sensors", metavar="LIST",
        help="comma-separated SensorOffset names, e.g. Sun0,Sun11,Coil0,Mag1",
    )
    generate.add_argument(
        "--armed", action="store_true",
        help="store the armed flag (default: unarmed, the first boot cannot deploy)",
    )
    generate.add_argument("--binary", metavar="PATH", help="write the 48 raw bytes here")
    generate.add_argument("--header", metavar="PATH", help="write a C header here")
    generate.add_argument(
        "--header-symbol", default="STARTUP_FRAM_IMAGE", metavar="NAME",
        help="C array name used by --header (default: STARTUP_FRAM_IMAGE)",
    )
    generate.add_argument(
        "--overwrite", action="store_true",
        help="replace existing output files (default: exclusive creation fails)",
    )
    generate.set_defaults(func=cmd_generate)

    inspect = subparsers.add_parser(
        "inspect",
        help="decode and validate a 48-byte image or FRAM read-back",
        description=(
            "Decode both slots, the boot counter and the ADCS mask, and report"
            " every contract violation. Exits 1 when the image is invalid."
        ),
    )
    inspect.add_argument("image", metavar="PATH", help="48-byte image to inspect")
    inspect.add_argument("--json", action="store_true", help="print JSON instead of a table")
    inspect.set_defaults(func=cmd_inspect)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except startup_image.StartupImageError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
